--
-- Add Journals
--
CREATE TABLE journal_group
(
	id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	description VARCHAR(4096),
	image       VARBINARY(199000) DEFAULT NULL
);

CREATE TABLE journal_message
(
	id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	content VARCHAR(8192),
	title   VARCHAR(1024),
	image   VARBINARY(199000) DEFAULT NULL,
	read    BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE journal_favorite
(
	message_id BIGINT PRIMARY KEY,
	favorite    BOOLEAN NOT NULL
);

CREATE TABLE journal_comment_history
(
	id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	article_message_id BIGINT NOT NULL,
	comment_text      VARCHAR(8192),
	published         TIMESTAMP NOT NULL
);
CREATE INDEX idx_journal_comment_history_published ON journal_comment_history (published);
